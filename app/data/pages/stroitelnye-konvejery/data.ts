const relatedSlugs = [
  'pogruzochnye-lentochnye-konveyery',
  'peredvizhnye-lentochnye-konveyery',
  'konveyer-lentochnyy-zhelobchatyy',
  'pryamye-lentochnye-konveyery',
  'naklonnyj-lentochnyj-konvejer',
] satisfies BeltVariantSlug[];

const relatedConveyors: IndustrialSection[] = relatedSlugs.map((slug) => {
  const variant = beltVariantDefinitions.find((item) => item.slug === slug);
  if (!variant) throw new Error(`Связанный конвейер не найден: ${slug}`);

  return {
    title: variant.title,
    text: [variant.description],
    image: variant.image,
    imageAlt: `Пример конструкции: ${variant.title.toLowerCase()}`,
    imageFit: 'contain',
    href: `/${slug}/`,
  };
});

