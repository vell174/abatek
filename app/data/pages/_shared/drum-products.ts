export function getDrumProduct(slug: string): ProductPageOptions {
  const product = productData[slug];
  if (!product) throw new Error(`Drum product was not found: ${slug}`);
  const images: Record<string, string> = {
    'privodnoy-baraban-konveyera': 'drive-conveyor-drum-large.webp',
    'natyazhnoy-baraban-konveyera': 'tail-conveyor-drum-housing-clean.webp',
    'otklonyayushchiy-baraban-konveyera': 'idler-clean.png',
    'baraban-kovshovogo-elevatora': 'elevator-clean.webp',
    'baraban-lentochnoy-norii': 'noria-clean.webp',
    'futerovannyy-baraban-transportera': 'lagged-clean.webp',
    'planchatyy-baraban-transportera': 'slatted-clean.webp',
    'nestandartnyy-baraban-po-chertezham': 'custom-clean.webp',
    'baraban-iz-nerzhaveyushchey-stali': 'stainless-clean.webp',
  };
  const productImage = `/images/barabany/bright/${images[slug]}`;

  return {
    ...product,
    image: productImage,
    sections: product.sections.map((section) => ({ ...section, image: undefined })),
  };
}

